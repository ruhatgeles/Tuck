import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Clipboard history: watches the pasteboard, owns the global shortcut and the
/// floating history panel, and pastes the chosen item back into the previous app.
final class ClipboardController: NSObject, NSWindowDelegate {
    let store = ClipboardStore()
    weak var shelf: ShelfStore?
    /// Closes the shelf popover when an item is used from inside it.
    var closePopover: (() -> Void)?
    /// App that was frontmost before our popover activated Tuck; paste goes there.
    var previousApp: NSRunningApplication?
    /// Opens the menu bar popover on a given tab (set by the shelf controller).
    var openPopoverTab: ((Int) -> Void)?
    weak var popoverVC: ClipboardViewController?

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var ownChange = -1
    private var ignoreNext = false
    private var hotKey: HotKey?
    private var panel: KeyPanel?
    private var panelVC: ClipboardViewController?
    private var outsideClickMonitor: Any?

    /// Pasteboard types that mark passwords / temporary data. Never recorded.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]

    // MARK: Settings

    private let defaults = UserDefaults.standard
    var paused: Bool {
        get { defaults.bool(forKey: "clipPaused") }
        set { defaults.set(newValue, forKey: "clipPaused") }
    }
    var autoPaste: Bool {
        get { defaults.object(forKey: "clipAutoPaste") as? Bool ?? true }
        set { defaults.set(newValue, forKey: "clipAutoPaste") }
    }
    var clearOnQuit: Bool {
        get { defaults.bool(forKey: "clipClearOnQuit") }
        set { defaults.set(newValue, forKey: "clipClearOnQuit") }
    }
    var saveImages: Bool {
        get { defaults.object(forKey: "clipImages") as? Bool ?? true }
        set { defaults.set(newValue, forKey: "clipImages") }
    }
    var saveFiles: Bool {
        get { defaults.object(forKey: "clipFiles") as? Bool ?? true }
        set { defaults.set(newValue, forKey: "clipFiles") }
    }
    var ignoredApps: [String] {
        get { defaults.stringArray(forKey: "clipIgnoredApps") ?? [] }
        set { defaults.set(newValue, forKey: "clipIgnoredApps") }
    }
    /// Index into HotKey.presets, -1 = off.
    var hotKeyIndex: Int {
        get { defaults.object(forKey: "clipHotKey") as? Int ?? 0 }
        set { defaults.set(newValue, forKey: "clipHotKey"); registerHotKey() }
    }
    private(set) var hotKeyFailed = false
    var hotKeyTitle: String? {
        HotKey.presets.indices.contains(hotKeyIndex) && !hotKeyFailed ? HotKey.presets[hotKeyIndex].title : nil
    }

    // MARK: Lifecycle

    override init() {
        super.init()
        store.onChange = { [weak self] in
            self?.panelVC?.reload()
            self?.popoverVC?.reload()
        }
        registerHotKey()
        startMonitoring()
        // Debug aid: `Tuck --show-clipboard` opens the history panel at launch.
        if CommandLine.arguments.contains("--show-clipboard") {
            DispatchQueue.main.asyncAfter(deadline: .now() + 1) { [weak self] in self?.togglePanel() }
        }
    }

    func applicationWillTerminate() {
        if clearOnQuit { store.clear() }
        store.flush()
    }

    private func registerHotKey() {
        hotKey = nil
        hotKeyFailed = false
        guard HotKey.presets.indices.contains(hotKeyIndex) else { return }
        hotKey = HotKey(HotKey.presets[hotKeyIndex]) { [weak self] in self?.togglePanel() }
        hotKeyFailed = hotKey == nil
    }

    // MARK: Monitoring

    private func startMonitoring() {
        // Same approach as other clipboard managers: macOS has no change notification,
        // so check the cheap changeCount twice a second (coalesced by the system).
        let interval = max(0.1, defaults.double(forKey: "clipInterval").nonZero ?? 0.5)
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in self?.check() }
        t.tolerance = interval / 2
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChange else { return }
        lastChange = count
        guard count != ownChange, !paused else { return }
        if ignoreNext { ignoreNext = false; return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard Self.shouldRecord(types: types, app: app, ignoredApps: ignoredApps,
                                saveImages: saveImages, saveFiles: saveFiles) else { return }
        store.capture(pb, app: app)
    }

    /// Filtering rules: password managers / transient data, ignored apps, and the
    /// "save images / files" options.
    static func shouldRecord(types: Set<String>, app: String?, ignoredApps: [String],
                             saveImages: Bool, saveFiles: Bool) -> Bool {
        guard !types.isEmpty, types.isDisjoint(with: ignoredTypes) else { return false }
        if let app, ignoredApps.contains(app) { return false }
        let hasFiles = types.contains("public.file-url")
        let hasImage = types.contains("public.png") || types.contains("public.tiff") || types.contains("public.jpeg")
        let hasText = types.contains("public.utf8-plain-text") || types.contains("public.rtf")
        if hasFiles && !saveFiles { return false }
        if hasImage && !hasText && !hasFiles && !saveImages { return false }
        return true
    }

    func ignoreNextCopy() { ignoreNext = true }

    // MARK: Using an entry

    /// Copies the entry to the clipboard and (optionally) pastes it into the previous app.
    func use(_ entry: ClipEntry, plain: Bool, paste: Bool) {
        let pb = NSPasteboard.general
        guard store.write(entry, to: pb, plain: plain) else { NSSound.beep(); return }
        ownChange = pb.changeCount
        lastChange = pb.changeCount
        store.touch(entry.id)

        let fromPopover = panel == nil
        let target = fromPopover ? previousApp : nil
        closePanel()
        closePopover?()

        guard paste && autoPaste else { return }
        guard AXIsProcessTrusted() else {
            requestAccessibility()
            return
        }
        if let target, target != NSRunningApplication.current {
            target.activate()
        } else if fromPopover {
            NSApp.hide(nil)
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { Self.postCommandV() }
    }

    func addToShelf(_ entry: ClipEntry) {
        guard let shelf else { return }
        let pb = NSPasteboard(name: NSPasteboard.Name("tuck.transfer.\(UUID().uuidString)"))
        defer { pb.releaseGlobally() }
        if store.write(entry, to: pb) { shelf.ingest(pb) }
    }

    func ignoreApp(_ bundleID: String) {
        guard !ignoredApps.contains(bundleID) else { return }
        ignoredApps.append(bundleID)
    }

    private static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    func requestAccessibility() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    // MARK: Panel (global shortcut)

    func togglePanel() {
        if panel != nil { closePanel() } else { showPanel() }
    }

    private func showPanel() {
        let size = NSSize(width: 380, height: 470)
        let vc = ClipboardViewController(controller: self, inPanel: true)
        let p = KeyPanel(contentRect: NSRect(origin: .zero, size: size),
                         styleMask: [.borderless, .nonactivatingPanel, .fullSizeContentView],
                         backing: .buffered, defer: true)
        p.isOpaque = false
        p.backgroundColor = .clear
        p.hasShadow = true
        p.level = .popUpMenu
        p.isReleasedWhenClosed = false
        p.hidesOnDeactivate = false
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient, .ignoresCycle]
        p.delegate = self

        let effect = NSVisualEffectView(frame: NSRect(origin: .zero, size: size))
        effect.material = .menu
        effect.state = .active
        effect.blendingMode = .behindWindow
        effect.wantsLayer = true
        effect.layer?.cornerRadius = 12
        effect.layer?.masksToBounds = true
        effect.layer?.borderWidth = 0.5
        effect.layer?.borderColor = NSColor.separatorColor.cgColor
        vc.view.frame = effect.bounds
        vc.view.autoresizingMask = [.width, .height]
        effect.addSubview(vc.view)
        p.contentView = effect

        // Open at the mouse pointer, kept fully on screen.
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { NSMouseInRect(mouse, $0.frame, false) } ?? NSScreen.main!
        let vis = screen.visibleFrame
        var origin = NSPoint(x: mouse.x + 4, y: mouse.y - size.height - 4)
        origin.x = min(max(origin.x, vis.minX + 8), vis.maxX - size.width - 8)
        origin.y = min(max(origin.y, vis.minY + 8), vis.maxY - size.height - 8)
        p.setFrameOrigin(origin)

        panel = p
        panelVC = vc
        p.makeKeyAndOrderFront(nil)
        vc.focusSearch()
        // Any click in another app closes the panel, even if it never became key.
        outsideClickMonitor = NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDown, .rightMouseDown]) {
            [weak self] _ in self?.closePanel()
        }
    }

    func closePanel() {
        guard let p = panel else { return }
        panel = nil
        panelVC = nil
        if let outsideClickMonitor { NSEvent.removeMonitor(outsideClickMonitor) }
        outsideClickMonitor = nil
        p.orderOut(nil)
    }

    func windowDidResignKey(_ notification: Notification) {
        // Clicking anywhere else closes the panel (like a menu).
        if (notification.object as? NSWindow) === panel { closePanel() }
    }

    // MARK: Settings menu

    func settingsMenu() -> NSMenu {
        let menu = NSMenu()
        func item(_ title: String, _ sel: Selector, on: Bool? = nil, tag: Int = 0) -> NSMenuItem {
            let mi = NSMenuItem(title: title, action: sel, keyEquivalent: "")
            mi.target = self
            mi.tag = tag
            if let on { mi.state = on ? .on : .off }
            return mi
        }
        menu.addItem(item("Kaydı duraklat", #selector(togglePaused), on: paused))
        menu.addItem(item("Sonraki kopyayı yok say", #selector(ignoreNextAction)))
        menu.addItem(.separator())

        let shortcut = NSMenu()
        for (i, p) in HotKey.presets.enumerated() {
            shortcut.addItem(item(p.title, #selector(setHotKey(_:)), on: hotKeyIndex == i, tag: i))
        }
        shortcut.addItem(item("Kapalı", #selector(setHotKey(_:)), on: hotKeyIndex == -1, tag: -1))
        let shortcutItem = NSMenuItem(title: hotKeyFailed ? "Kısayol (⚠️ başka uygulama kullanıyor)" : "Kısayol",
                                      action: nil, keyEquivalent: "")
        shortcutItem.submenu = shortcut
        menu.addItem(shortcutItem)

        let limits = NSMenu()
        for n in [50, 100, 200, 500, 1000] {
            limits.addItem(item("\(n)", #selector(setLimit(_:)), on: store.limit == n, tag: n))
        }
        let limitItem = NSMenuItem(title: "Geçmiş boyutu", action: nil, keyEquivalent: "")
        limitItem.submenu = limits
        menu.addItem(limitItem)

        let ax = AXIsProcessTrusted()
        menu.addItem(item(ax ? "Seçince otomatik yapıştır" : "Seçince otomatik yapıştır (izin gerekli)",
                          #selector(toggleAutoPaste), on: autoPaste))
        menu.addItem(item("Görselleri kaydet", #selector(toggleImages), on: saveImages))
        menu.addItem(item("Dosyaları kaydet", #selector(toggleFiles), on: saveFiles))
        menu.addItem(item("Çıkışta geçmişi temizle (📌 hariç)", #selector(toggleClearOnQuit), on: clearOnQuit))

        if !ignoredApps.isEmpty {
            let apps = NSMenu()
            for (i, id) in ignoredApps.enumerated() {
                apps.addItem(item(Self.appName(id) + " — kaldır", #selector(unignoreApp(_:)), on: true, tag: i))
            }
            let appsItem = NSMenuItem(title: "Yok sayılan uygulamalar", action: nil, keyEquivalent: "")
            appsItem.submenu = apps
            menu.addItem(appsItem)
        }

        menu.addItem(.separator())
        menu.addItem(item("Geçmişi temizle (📌 hariç)", #selector(clearHistory)))
        menu.addItem(item("Her şeyi sil (📌 dahil)…", #selector(clearEverything)))
        return menu
    }

    @objc private func togglePaused() { paused.toggle() }
    @objc private func ignoreNextAction() { ignoreNextCopy() }
    @objc private func setHotKey(_ sender: NSMenuItem) { hotKeyIndex = sender.tag }
    @objc private func setLimit(_ sender: NSMenuItem) { store.limit = sender.tag }
    @objc private func toggleImages() { saveImages.toggle() }
    @objc private func toggleFiles() { saveFiles.toggle() }
    @objc private func toggleClearOnQuit() { clearOnQuit.toggle() }
    @objc private func toggleAutoPaste() {
        autoPaste.toggle()
        if autoPaste && !AXIsProcessTrusted() { requestAccessibility() }
    }
    @objc private func unignoreApp(_ sender: NSMenuItem) {
        var list = ignoredApps
        guard list.indices.contains(sender.tag) else { return }
        list.remove(at: sender.tag)
        ignoredApps = list
    }
    @objc func clearHistory() { store.clear() }
    @objc private func clearEverything() {
        let alert = NSAlert()
        alert.messageText = "Tüm pano geçmişi silinsin mi?"
        alert.informativeText = "Sabitlenmiş (📌) öğeler de silinir. Bu işlem geri alınamaz."
        alert.addButton(withTitle: "Hepsini Sil")
        alert.addButton(withTitle: "Vazgeç")
        alert.buttons.first?.hasDestructiveAction = true
        NSApp.activate(ignoringOtherApps: true)
        if alert.runModal() == .alertFirstButtonReturn { store.clear(includingPinned: true) }
    }

    // MARK: Helpers

    private static var appNames: [String: String] = [:]
    static func appName(_ bundleID: String) -> String {
        if let n = appNames[bundleID] { return n }
        let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)
        let name = url.map { FileManager.default.displayName(atPath: $0.path).replacingOccurrences(of: ".app", with: "") }
            ?? bundleID
        appNames[bundleID] = name
        return name
    }

    private static let appIcons = NSCache<NSString, NSImage>()
    static func appIcon(_ bundleID: String?) -> NSImage? {
        guard let bundleID else { return nil }
        if let i = appIcons.object(forKey: bundleID as NSString) { return i }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        appIcons.setObject(icon, forKey: bundleID as NSString)
        return icon
    }
}

/// Borderless panels can't become key by default; we need keyboard input for search.
final class KeyPanel: NSPanel {
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { false }
}

private extension Double {
    var nonZero: Double? { self == 0 ? nil : self }
}
